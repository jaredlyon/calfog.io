HIST = 'Open-Meteo Historical-Forecast best-match (non-vintage approximate proxy)'
FORWARD = 'Open-Meteo Forecast API most-recent analysis hours (retrieval snapshot)'


def jsonl(tmp_path, name, rows):
    p = tmp_path / name
    p.write_text(''.join(json.dumps(r) + '\n' for r in rows))
    return pd.read_json(p, lines=True, convert_dates=False, convert_axes=False)


def prediction(issue='2026-01-01T08:00:00Z', **kw):
    return dict(site='location_6', task='nowcast', model='xgboost', issue_time_utc=issue,
                p_fog=.9, pmf=[.9/5]*5+[.1/13]*13, feed_source=HIST, faithful=False,
                nonfaithful_features=['soil_temperature_0_to_7cm'],
                costgrid_decisions={str(k): True for k in (1, 3, 5, 10, 20)}, **kw)


