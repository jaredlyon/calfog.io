@pytest.mark.parametrize('start', ['2026-03-08T00:00:00Z', '2026-11-01T00:00:00Z'])
def test_shadow4_fixed_pst_keeps_all_utc_hours(tmp_path, start):
    times = pd.date_range(start, periods=36, freq='h')
    frame = jsonl(tmp_path, 'weather.jsonl', [dict(time=t.isoformat(), temperature_2m=i,
        dew_point_2m=0) for i, t in enumerate(times)])
    converted = common.raw_hourly_to_frame({'timezone': 'UTC', 'hourly': frame.to_dict('list')})
    expected = times.tz_convert('Etc/GMT+8').tz_localize(None)
    assert converted.time.tolist() == expected.tolist()
    assert converted.time.diff().dropna().eq(pd.Timedelta(hours=1)).all()


def run_labels(tmp_path, monkeypatch, now, payload):
    jsonl(tmp_path, 'metars.jsonl', payload)
    payload = [json.loads(x) for x in (tmp_path / 'metars.jsonl').read_text().splitlines()]
    class Response:
        content = json.dumps(payload).encode()
        status_code = 200
        url = 'offline://synthetic'
        def json(self): return payload
        def raise_for_status(self): pass
    real = pd.Timestamp
    class Clock(real):
        @classmethod
        def now(cls, tz=None): return real(now).tz_convert(tz)
    monkeypatch.setattr(labels.pd, 'Timestamp', Clock)
    monkeypatch.setattr(labels, 'SITES', {'location_6': {'airport': 'KMAE'}})
    monkeypatch.setattr(labels, 'SHADOW', tmp_path)
    monkeypatch.setattr(labels, 'append_manifest', lambda entry: None)
    monkeypatch.setattr(labels.requests, 'get', lambda *a, **k: Response())
    labels.main([])
    return [json.loads(x) for x in (tmp_path / 'outcomes_forward.jsonl').read_text().splitlines()]


def test_shadow4_lead_keys_use_fixed_pst_in_summer(tmp_path, monkeypatch):
    ts = pd.date_range('2026-07-01T08:00:00Z', '2026-07-02T17:00:00Z', freq='h')
