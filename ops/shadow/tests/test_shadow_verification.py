@pytest.mark.parametrize('issued,allowed', [
    ('2026-07-02T01:59:45Z', True), ('2026-07-02T02:00:01Z', False)])
def test_shadow1_inference_completion_cutoff(tmp_path, monkeypatch, issued, allowed):
    row = jsonl(tmp_path, 'issuance.jsonl', [dict(issued=issued,
        retrieved='2026-07-02T01:59:30Z', issue='2026-07-02T02:00:00Z')]).iloc[0]
    monkeypatch.setattr(common, 'utc_now', lambda: pd.Timestamp(row.issued), raising=False)
    def build():
        return common.build_log_record(site='location_6', task='lead_time', issue_time_utc=row.issue,
            target_window_utc={}, model='xgboost', p_fog=.5, pmf=[1/18]*18, feed_source=FORWARD,
            feature_end_time_utc=row.issue, costgrid_decisions={}, created_utc=row.retrieved)
    if not allowed:
        with pytest.raises(ValueError, match='cutoff'): build()
    else:
        result = build()
        assert result['issued_at_utc'] == row.issued
        assert result['created_utc'] == row.retrieved


